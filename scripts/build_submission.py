#!/usr/bin/env python3
"""Retired entry point for the noncompliant legacy ASB experiment runner.

The previous runner used private metric/holdout/writer implementations and
could continue after incomplete registry comparisons. It is intentionally
fail-closed. No candidate is generated by this command.
"""
from __future__ import annotations

import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main() -> int:
    card_path = ROOT / "evidence/run-card.json"
    if not card_path.is_file():
        print("STOP: canonical run card is missing; no output was created.")
        return 3
    card = json.loads(card_path.read_text())
    if card.get("authorized_to_download_and_submit") is not True:
        print(
            "STOP: no candidate is authorized. The legacy ASB runner is retired; "
            "no TIFF was written. Resolve the shared protocol ambiguity and implement "
            "a selector-gated pipeline using the pinned shared evaluator/writer."
        )
        return 2
    print(
        "STOP: authorization alone does not re-enable the retired runner. "
        "Use a reviewed implementation based on vendor/gems57."
    )
    return 2


if __name__ == "__main__":
    raise SystemExit(main())
